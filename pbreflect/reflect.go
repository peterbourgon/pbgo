package pbreflect

import (
	"reflect"
	"runtime"
)

// DirectlyImplements reports whether x satisfies interface T via methods
// declared directly on x's type, rather than methods promoted from an embedded
// field. T must be an interface type; otherwise the call returns the zero
// value and false.
func DirectlyImplements[T any](x any) (T, bool) {
	var zero T

	iface := reflect.TypeFor[T]()
	if iface.Kind() != reflect.Interface {
		return zero, false
	}

	t, ok := x.(T)
	if !ok {
		return zero, false
	}

	xt := reflect.TypeOf(x)
	for im := range iface.Methods() {
		if directlyImplementsMethod(xt, im.Name) {
			continue // method is implemented on value receiver
		}

		if xt.Kind() == reflect.Pointer && directlyImplementsMethod(xt.Elem(), im.Name) {
			continue // method is implemented on pointer receiver
		}

		return zero, false
	}

	return t, true
}

func directlyImplementsMethod(t reflect.Type, name string) bool {
	m, ok := t.MethodByName(name)
	if !ok {
		return false
	}

	pc := m.Func.Pointer()
	fn := runtime.FuncForPC(pc)
	if fn == nil {
		return false
	}

	file, _ := fn.FileLine(pc)
	return file != "<autogenerated>"
}
