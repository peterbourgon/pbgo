package pbreflect

import (
	"reflect"
	"runtime"
)

// DirectlyImplements reports whether x satisfies interface T via methods
// declared directly on x's type, rather than methods promoted from an embedded
// field. T must be an interface type.
func DirectlyImplements[T any](x any) (T, bool) {
	var zero T
	iface := reflect.TypeFor[T]()
	if iface.Kind() != reflect.Interface {
		return zero, false
	}

	t, ok := x.(T)
	if !ok {
		return zero, false
	}

	xt := reflect.TypeOf(x)
	for im := range iface.Methods() {
		m, ok := xt.MethodByName(im.Name)
		if !ok {
			return zero, false
		}
		pc := m.Func.Pointer()
		fn := runtime.FuncForPC(pc)
		if fn == nil {
			return zero, false
		}
		if file, _ := fn.FileLine(pc); file == "<autogenerated>" {
			return zero, false
		}
	}
	return t, true
}
